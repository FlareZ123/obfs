'use strict';

const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const {main}=require('../src/cli');
const {atomicWrite}=require('../src/atomic');
const {directBareRequires}=require('../src/sno-bare-audit');

/**
 * @param {string} filename
 * @returns {string}
 */
function run(filename) {
  const program=spawnSync(process.execPath,['--eval',
    'process.stdout.write(String(require(process.argv[1])))',filename],
  {encoding:'utf8',timeout:15000});
  if(program.error)throw program.error;
  assert.equal(program.status,0,program.stderr);
  return program.stdout;
}

/**
 * @param {(directory:string)=>Promise<void>} callback
 * @returns {Promise<void>}
 */
async function fixture(callback) {
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'obfs-sno-bare-audit-'));
  try {await callback(temp);}
  finally{await fs.rm(temp,{recursive:true,force:true});}
}

test('opt-in SNO detects different external bare dependency before publication',async()=>{
  await fixture(async temp=>{
    const source=path.join(temp,'source');
    const out=path.join(temp,'out');
    await atomicWrite(path.join(source,'entry.cjs'),
      "const privateMarker=13;module.exports=require('audit-example')+privateMarker;");
    await atomicWrite(path.join(source,'node_modules','audit-example','index.js'),
      'module.exports=103;');
    await atomicWrite(path.join(out,'node_modules','audit-example','index.js'),
      'module.exports=107;');
    assert.equal(run(path.join(source,'entry.cjs')),'116');

    await assert.rejects(
      main('sno',['--root',source,'--entry','entry.cjs',
        '--out',out,'--seed','audit-different-packages','--audit-bare-cjs']),
      /SNO bare dependency resolution differs: entry\.cjs -> audit-example/u
    );
    await assert.rejects(fs.stat(path.join(out,'sno-entry.cjs')),{code:'ENOENT'});
    await assert.rejects(fs.stat(path.join(out,'entry.cjs')),{code:'ENOENT'});
    assert.equal(await fs.readFile(path.join(out,'node_modules',
      'audit-example','index.js'),'utf8'),'module.exports=107;');
  });
});

test('opt-in SNO accepts one shared external dependency and preserves generated bytes',async()=>{
  await fixture(async temp=>{
    const root=path.join(temp,'project');
    const source=path.join(root,'source');
    const output=path.join(root,'output');
    const control=path.join(root,'control');
    await atomicWrite(path.join(root,'node_modules','audit-example','index.js'),
      'module.exports=103;');
    await atomicWrite(path.join(source,'entry.cjs'),
      "const privateMarker=13;module.exports=require('audit-example')+privateMarker;");
    const args=['--root',source,'--entry','entry.cjs',
      '--seed','audit-one-package'];
    await main('sno',[...args,'--out',output,'--audit-bare-cjs']);
    await main('sno',[...args,'--out',control]);

    for(const filename of ['entry.cjs','sno-entry.cjs']) {
      assert.deepEqual(
        await fs.readFile(path.join(output,filename)),
        await fs.readFile(path.join(control,filename))
      );
    }
    assert.equal(run(path.join(source,'entry.cjs')),'116');
    assert.equal(run(path.join(output,'sno-entry.cjs')),'116');
  });
});

test('opt-in audit refuses an external package missing from the intended output',async()=>{
  await fixture(async temp=>{
    const source=path.join(temp,'source');
    const out=path.join(temp,'out');
    await atomicWrite(path.join(source,'entry.cjs'),
      "module.exports=require('audit-example');");
    await atomicWrite(path.join(source,'node_modules','audit-example','index.js'),
      'module.exports=211;');
    await assert.rejects(
      main('sno',['--root',source,'--entry','entry.cjs',
        '--out',out,'--audit-bare-cjs']),
      /SNO output bare dependency could not resolve/u
    );
    await assert.rejects(fs.stat(path.join(out,'sno-entry.cjs')),{code:'ENOENT'});
  });
});

test('audit scope is direct bare CJS calls and refuses lexical require shadowing',()=>{
  const files=[
    {path:'entry.cjs',sourceType:'commonjs',code:
      "module.exports=require('audit-example')+require('node:path').sep.length;"},
    {path:'nested/logic.cjs',sourceType:'commonjs',code:
      "module.exports=require('./relative.cjs')+require('#local');"},
    {path:'dot.cjs',sourceType:'commonjs',code:
      "module.exports=require('.hidden-pkg')+require('audit-example',{irrelevant:true});"},
    {path:'esm.mjs',sourceType:'module',code:
      "import x from 'audit-example';export default x;"}
  ];
  const collected=directBareRequires(files);
  assert.deepEqual([...collected],[
    ['entry.cjs',['audit-example']],
    ['dot.cjs',['.hidden-pkg','audit-example']]
  ]);
  assert.throws(()=>directBareRequires([{
    path:'entry.cjs',sourceType:'commonjs',
    code:"function local(require){return require('audit-example');}module.exports=local;"
  }]),/cannot prove unshadowed require/u);
});

test('SNO-only audit flag is refused by COO and SCO',async()=>{
  await fixture(async temp=>{
    const source=path.join(temp,'source');
    await atomicWrite(path.join(source,'client.js'),'globalThis.result=13;');
    for(const mode of /** @type {const} */(['coo','sco'])) {
      await assert.rejects(main(mode,[
        '--root',source,'--entry','client.js','--audit-bare-cjs'
      ]),/--audit-bare-cjs is SNO-only/u);
    }
  });
});
