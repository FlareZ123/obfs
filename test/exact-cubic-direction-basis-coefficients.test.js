'use strict';

const test=require('node:test');
const assert=require('node:assert/strict');
const {makeCubicDefectContractor}=require('../sims/exact-cubic-compatible-cegar');
const {masksOfWeight}=require('../sims/bounded-degree-oracle-functional-clone');

const WIDTH=32;

/** @param {number} seed @returns {()=>number} */
function xorshift32(seed){
  let state=seed>>>0;
  return ()=>{
    state^=state<<13;
    state^=state>>>17;
    state^=state<<5;
    return state>>>0;
  };
}

/**
 * Independent coefficient generator; output remains in an 8-bit proper
 * subspace to ensure the resulting rank comparison is not trivially 32.
 * @param {number} seed
 * @returns {{bits:number,degree:number,coefficients:Array<[number,number]>,queryCount:number}}
 */
function makeCubicModel(seed){
  const next=xorshift32(seed);
  /** @type {Array<[number,number]>} */
  const coefficients=[];
  for(let degree=0;degree<=3;degree++){
    for(const mask of masksOfWeight(WIDTH,degree)){
      coefficients.push([mask,next()&255]);
    }
  }
  return {bits:WIDTH,degree:3,coefficients,queryCount:coefficients.length};
}

/**
 * A GF(2) cubic defect is quadratic in x. Its mixed direction-pair
 * first-order x coefficients are linear combinations of second-order
 * coefficients in one fixed direction:
 *
 * L_i(u+v)+L_i(u)+L_i(v) = XOR_{j != i, u_j=1} Q_{ij}(v).
 *
 * The second-order coefficients Q_{ij}(v) themselves are linear in v.
 * These identities are a direct check of the all-x basis-direction span
 * theorem without relying only on a saturated full-output rank.
 */
test('cubic pair-direction defects are generated by basis-direction quadratic x coefficients',()=>{
  const directions=[0x12345678,0x80000001,0xa5a55a5a,0x01010101,0x0f0f0f0f,0x55555555];
  let nonzeroMixed=0;
  let checked=0;
  for(const seed of [0x7143e5b9,0x39b7d7ea,0x1f83d9ab]){
    const contract=makeCubicDefectContractor(makeCubicModel(seed));
    for(let p=0;p<directions.length;p++){
      const u=directions[p]>>>0;
      const a=contract(u);
      for(let q=p+1;q<directions.length;q++){
        const v=directions[q]>>>0;
        const b=contract(v);
        const combined=contract((u^v)>>>0);
        for(let i=0;i<WIDTH;i++){
          let expected=0;
          for(let j=0;j<WIDTH;j++){
            if(i===j||((u>>>j)&1)===0)continue;
            const lo=Math.min(i,j),hi=Math.max(i,j);
            expected^=b.second[lo*WIDTH+hi];
          }
          const actual=(combined.first[i]^a.first[i]^b.first[i])>>>0;
          assert.equal(actual,expected>>>0,
            'a pair-direction coefficient escaped the single-direction span');
          if(actual!==0)nonzeroMixed++;
          checked++;
        }
        for(let i=0;i<WIDTH;i++){
          for(let j=i+1;j<WIDTH;j++){
            const index=i*WIDTH+j;
            assert.equal((combined.second[index]^a.second[index]^b.second[index])>>>0,
              0,'quadratic-in-x coefficient was nonlinear in the direction');
            checked++;
          }
        }
      }
    }
  }
  assert.ok(nonzeroMixed>0,'ensure the test exercises genuine cubic mixed terms');
  assert.equal(checked,3*15*(32+496));
});
