'use strict';

const assert=require('node:assert/strict');
const {test}=require('node:test');
const vm=require('node:vm');
const {lowerWasmI32Functions}=require('../src/wasm-i32');
const {obfuscateFiles}=require('../src/core');
const {parse}=require('../src/ast');
const {recoverPublicWasmExpression}=require('../sims/wasm-i32-static-recover');

const candidates=[
  {arity:'a,b,c',expression:'(a?((b^c)&255):((~b)|c))',unsigned:false},
  {arity:'a,b,c,d',expression:'((a&1)?(b>>>c):(b>>>d))',unsigned:true},
  {arity:'a,b,c,d',expression:'((a^b)?(a?b:c):(d?c:b))',unsigned:false},
  {arity:'a,b,c,d',expression:'(((a?b:c)^d)|((a&7)?c:d))',unsigned:false},
  {arity:'a,b,c,d',expression:'((a?(b>>>1):c)^d)',unsigned:false},
  {arity:'a,b,c,d',expression:'((a?b:c)?d:(~d))',unsigned:false},
  {arity:'a,b,c,d',expression:'((a?((b>>>c)|(d<<1)):((~c)&d))^a)',unsigned:false}
];

/** @param {string} code @returns {(...args:number[])=>number} */
function load(code){
  const module={exports:null};
  vm.runInNewContext(code,{module,globalThis},{timeout:3000});
  return /** @type {(...args:number[])=>number} */(
    /** @type {unknown} */ (module.exports));
}

/**
 * Canonical syntax independently generated by Acorn, not the Wasm decoder.
 * @param {string} expression
 * @returns {string}
 */
function canonical(expression){
  const ast=parse('function f(a,b,c,d){return '+expression+';}','commonjs');
  const argument=ast.body[0].body.body[0].argument;
  /** @param {import('../src/ast').AstNode} node @returns {string} */
  function print(node){
    if(node.type==='Identifier')return node.name;
    if(node.type==='Literal')return String(node.value);
    if(node.type==='UnaryExpression'&&node.operator==='-'&&node.argument.type==='Literal')
      return String(-node.argument.value);
    if(node.type==='UnaryExpression'&&node.operator==='~')
      return '(~'+print(node.argument)+')';
    if(node.type==='BinaryExpression')
      return '('+print(node.left)+node.operator+print(node.right)+')';
    if(node.type==='ConditionalExpression')
      return '('+print(node.test)+'?'+print(node.consequent)+':'+print(node.alternate)+')';
    throw new TypeError('Unsupported canonical AST node '+node.type);
  }
  return print(argument);
}

const boundary=[-2147483648,-1,0,1,2,31,32,2147483647];
let rng=0x698ac27;
/** @returns {number} */
function i32(){
  rng^=rng<<13;
  rng^=rng>>>17;
  rng^=rng<<5;
  return rng|0;
}

test('typed conditional Wasm select preserves 1-4-input ternary branches and exposes exact static AST',()=>{
  let variants=0,comparisons=0;
  for(let index=0;index<candidates.length;index++){
    const candidate=candidates[index];
    const source='function f('+candidate.arity+'){return '+candidate.expression+';}module.exports=f;';
    const original=load(source);
    const parameters=candidate.arity.split(',');
    for(let seed=0;seed<12;seed++){
      const emitted=lowerWasmI32Functions(source,'commonjs',{
        seed:'i32-conditional-'+index+'-'+seed,names:['f']
      });
      assert.equal(emitted.functions,1,source);
      const lowered=load(emitted.code);
      const recovered=recoverPublicWasmExpression(emitted.code,parameters);
      assert.equal(recovered.expression,canonical(candidate.expression));
      const cloned=load('function f('+candidate.arity+'){return '+recovered.expression+';}module.exports=f;');
      const bytes=emitted.code.match(/Uint8Array\.from\((\[[0-9,]+\])\)/u);
      assert.ok(bytes);
      const binary=Uint8Array.from(JSON.parse(bytes[1]));
      assert.ok(binary.includes(0x1b),'Wasm select opcode must be emitted');
      const wasm=/** @type {(...args:number[])=>number} */ (
        new WebAssembly.Instance(new WebAssembly.Module(binary)).exports.f);
      for(let trial=0;trial<128;trial++){
        const args=parameters.map((_,i)=>trial<boundary.length ?
          boundary[(trial+i)%boundary.length]:i32());
        const expected=original(...args);
        assert.ok(Object.is(lowered(...args),expected),'Lowered '+index+'/'+seed+'/'+trial);
        assert.ok(Object.is(cloned(...args),expected),'Reconstructed '+index+'/'+seed+'/'+trial);
        assert.ok(Object.is(candidate.unsigned?(wasm(...args)>>>0):wasm(...args),expected),
          'Public binary clone '+index+'/'+seed+'/'+trial);
        comparisons++;
      }
      variants++;
    }
  }
  assert.equal(variants,candidates.length*12);
  assert.equal(comparisons,candidates.length*12*128);
  console.log(JSON.stringify({conditionalVariants:variants,staticExactReconstructions:variants,
    typedComparisons:comparisons,seed:'0x698ac27'}));
});

test('conditional signed/unsigned ambiguous return and impure expression trees decline unchanged',()=>{
  for(const code of [
    'function f(a,b,c){return a?(b>>>1):c;}',
    'function f(a,b,c){return a?b:(c>>>1);}',
    'function f(a,b,c,d){return a?(b>>>1):(c?(d>>>2):c);}',
    'function f(a,b){return a?run(b):b;}',
    'function f(a,b){return a?(b+1):b;}',
    'function f(a,b){return a?[1]:b;}',
    'function f(a,b){if(a)return b;return ~b;}',
    'function f(a,b){return a?b:{}.value;}'
  ]){
    const source=code+'module.exports=f;';
    const result=lowerWasmI32Functions(source,'commonjs',{
      seed:'conditional-refusal',names:['f']
    });
    assert.equal(result.functions,0,code);
    assert.equal(result.declined,1,code);
    assert.equal(result.code,source,code);
  }
});

test('conditional bitvector emit integrates with COO ESM and SNO CommonJS',async()=>{
  const esm='export function f(a,b,c){return a?((b^c)&255):((~b)|c);}';
  const emitted=obfuscateFiles([{path:'conditional.mjs',sourceType:'module',code:esm}],{
    mode:'coo',seed:'conditional-esm',strings:false,properties:false,identifiers:false,
    experimentalWasmI32:{'conditional.mjs':['f']}
  });
  assert.equal(emitted.files[0].metrics.wasmI32Functions,1);
  const original=await import('data:text/javascript;base64,'+Buffer.from(esm).toString('base64'));
  const lowered=await import('data:text/javascript;base64,'+
    Buffer.from(String(emitted.files[0].code)).toString('base64'));
  for(let i=0;i<512;i++){
    const args=[i32(),i32(),i32()];
    assert.equal(lowered.f(...args),original.f(...args));
  }
  const cjs='function f(a,b,c,d){return (a&1)?(b>>>c):(b>>>d);}module.exports=f;';
  const generated=obfuscateFiles([{path:'conditional.cjs',sourceType:'commonjs',code:cjs}],{
    mode:'sno',seed:'conditional-sno',strings:false,properties:false,identifiers:false,
    experimentalWasmI32:{'conditional.cjs':['f']}
  });
  assert.equal(generated.files[0].metrics.wasmI32Functions,1);
  const native=load(cjs),compiled=load(String(generated.files[0].code));
  for(let i=0;i<512;i++){
    const args=[i32(),i32(),i32(),i32()];
    assert.equal(compiled(...args),native(...args));
  }
});
