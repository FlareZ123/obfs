'use strict';

const {test}=require('node:test');
const assert=require('node:assert/strict');
const {runBasisSpanCheck,binaryRank,enumerateSpan,compareDefectSpans}=
  require('../sims/derivative-basis-span');

test('general defect span is generated by input-subspace basis directions',()=>{
  const result=runBasisSpanCheck();
  assert.deepEqual(result,{
    exhaustiveWidthTwoCases:2560,
    randomCases:1500,
    seed:0x71d1ae57
  });
});

test('basis-span verifier handles rank zero, non-coordinate basis and full rank',()=>{
  assert.equal(binaryRank([],5),0);
  assert.equal(binaryRank([0,2,2,4,6],5),2);
  assert.deepEqual(enumerateSpan([3,5]),[0,3,5,6]);
  assert.equal(compareDefectSpans([0,1,2,3],[3,1],2),0);
  assert.equal(compareDefectSpans([0,0,0,1],[3,2],2),1);
});
