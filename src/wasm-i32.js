'use strict';

const {createHash}=require('node:crypto');
const {parse,walk,applyEdits,observesFunctionSource}=require('./ast');

/** @typedef {import('./ast').AstNode} AstNode */
/** @typedef {{code:string,functions:number,instructions:number,wasmBytes:number,declined:number}} WasmI32Result */

/** @type {Readonly<Record<string,number>>} */
const OPS=Object.freeze({'&':0x71,'|':0x72,'^':0x73,'<<':0x74,'>>':0x75,'>>>':0x76});

/** Encode an unsigned LEB128 integer. @param {number} value @returns {number[]} */
function uleb(value) {
  /** @type {number[]} */
  const bytes=[];
  do {
    let b=value&127;
    value=Math.floor(value/128);
    if(value)b|=128;
    bytes.push(b);
  } while(value);
  return bytes;
}

/** Encode a signed 32-bit LEB128 integer. @param {number} value @returns {number[]} */
function sleb(value) {
  /** @type {number[]} */
  const bytes=[];
  let next=value|0;
  for(;;) {
    const byte=next&127;
    next>>=7;
    const done=(next===0 && (byte&64)===0)||(next===-1 && (byte&64)!==0);
    bytes.push(done?byte:byte|128);
    if(done)return bytes;
  }
}

/** @param {number[]} data @returns {number[]} */
function section(data) {return [...uleb(data.length),...data];}
/** @param {string} name @returns {number[]} */
function utf8(name) {
  const data=[...Buffer.from(name,'utf8')];
  return [...uleb(data.length),...data];
}

/**
 * Accept a deliberately small side-effect-free JS bitvector grammar.
 * The caller must establish primitive signed Int32 Number input types.
 * @param {AstNode} node
 * @param {readonly string[]} parameters
 * @param {number} depth
 * @returns {boolean}
 */
function accepted(node,parameters,depth=0) {
  if(depth>16)return false;
  if(node.type==='Identifier')return parameters.includes(node.name);
  if(node.type==='Literal')return typeof node.value==='number' &&
    Number.isInteger(node.value)&&node.value>=-2147483648&&node.value<=2147483647;
  if(node.type==='ConditionalExpression') {
    // All three operands are pure primitive-i32 expressions. Evaluating both
    // arms eagerly with Wasm select cannot trigger source-level side effects.
    return accepted(node.test,parameters,depth+1) &&
      accepted(node.consequent,parameters,depth+1) &&
      accepted(node.alternate,parameters,depth+1);
  }
  if(node.type==='UnaryExpression'&&node.prefix&&node.operator==='~') {
    return accepted(node.argument,parameters,depth+1);
  }
  if(node.type==='UnaryExpression'&&node.prefix&&node.operator==='-'&&
      node.argument.type==='Literal'&&typeof node.argument.value==='number'&&
      Number.isInteger(node.argument.value)) {
    return -node.argument.value>=-2147483648&&-node.argument.value<=2147483647;
  }
  return node.type==='BinaryExpression'&&Object.hasOwn(OPS,node.operator)&&
    accepted(node.left,parameters,depth+1)&&accepted(node.right,parameters,depth+1);
}

/**
 * Native >>> produces an unsigned Number while other allowed terminal bitwise
 * expressions and typed inputs produce signed Int32 Numbers. An outer ternary
 * can return either representation, so only a uniform result kind may cross
 * the Wasm i32 boundary. Inner ternaries are safe when a bitwise parent
 * performs ToInt32 on their selected value before returning.
 * @param {AstNode} node
 * @returns {'signed'|'unsigned'|'mixed'}
 */
function resultKind(node) {
  if(node.type==='ConditionalExpression') {
    const yes=resultKind(node.consequent);
    const no=resultKind(node.alternate);
    return yes===no?yes:'mixed';
  }
  return node.type==='BinaryExpression'&&node.operator==='>>>'?'unsigned':'signed';
}

/** @param {AstNode} node @returns {boolean} */
function simpleOperand(node) {return node.type==='Identifier'||node.type==='Literal'||
  node.type==='UnaryExpression'&&node.operator==='-'&&node.argument.type==='Literal';}

/**
 * Emit an i32 operator graph. Seeded diversification uses masked constants
 * and, at most twice, Boolean identities on direct primitive leaves.
 * The generated bytecode has no encryption key and remains extractable.
 * @param {AstNode} node
 * @param {readonly string[]} parameters
 * @param {Buffer} entropy
 * @param {{position:number,steps:number,diversified:number}} state
 * @param {'auto'|'select'|'if'} conditionalStrategy
 * @returns {number[]}
 */
function emit(node,parameters,entropy,state,conditionalStrategy) {
  if(node.type==='Identifier') {
    const index=parameters.indexOf(node.name);
    if(index<0)throw Error('Compiler parameter proof mismatch');
    state.steps++;
    return [0x20,index];
  }
  let constant=null;
  if(node.type==='Literal')constant=/** @type {number} */(node.value);
  else if(node.type==='UnaryExpression'&&node.operator==='-') {
    constant=-/** @type {number} */(node.argument.value);
  }
  if(constant!==null) {
    const mask=entropy.readInt32LE((state.position++%8)*4);
    state.steps+=3;
    return [0x41,...sleb((constant^mask)|0),0x41,...sleb(mask),0x73];
  }
  if(node.type==='ConditionalExpression') {
    // Choose between eager Wasm select and lazy structured if/else.
    // Source expressions are pure i32 primitives. Either lowering preserves
    // behaviour, while a strongly asymmetric pair of arms warrants lazy
    // execution to avoid paying for the unselected expensive branch.
    const yes=emit(node.consequent,parameters,entropy,state,conditionalStrategy);
    const no=emit(node.alternate,parameters,entropy,state,conditionalStrategy);
    const predicate=emit(node.test,parameters,entropy,state,conditionalStrategy);
    const shortest=Math.min(yes.length,no.length);
    const longest=Math.max(yes.length,no.length);
    const lazy=conditionalStrategy==='if'||
      conditionalStrategy==='auto'&&longest+shortest>=48&&longest>=3*shortest;
    state.steps+=lazy?3:1;
    if(lazy) {
      // The result type 0x7f is i32. Unlike select, Wasm if only executes
      // the chosen branch; both paths produce exactly one i32 value.
      return [...predicate,0x04,0x7f,...yes,0x05,...no,0x0b];
    }
    return [...yes,...no,...predicate,0x1b];
  }
  if(node.type==='UnaryExpression') {
    const body=emit(node.argument,parameters,entropy,state,conditionalStrategy);
    state.steps+=2;
    return [0x41,0x7f,...body,0x73];
  }
  if(node.type!=='BinaryExpression')throw Error('Compiler validation mismatch');
  const left=emit(node.left,parameters,entropy,state,conditionalStrategy);
  const right=emit(node.right,parameters,entropy,state,conditionalStrategy);
  const opcode=OPS[node.operator];
  if((node.operator==='&'||node.operator==='|'||node.operator==='^')&&
     simpleOperand(node.left)&&simpleOperand(node.right)&&
     state.diversified<2 && (entropy[state.position++%entropy.length]&1)===1) {
    // Duplicate reads are pure for the restricted Number-only leaves.
    const [first,second]=node.operator==='&'?[0x72,0x73]:
      node.operator==='|'?[0x71,0x73]:[0x72,0x71];
    state.steps+=6;
    state.diversified++;
    return [...left,...right,first,...left,...right,second,0x73];
  }
  state.steps++;
  return [...left,...right,opcode];
}

/**
 * Construct a WebAssembly module with one to four i32 arguments and one i32 result.
 * @param {number[]} body
 * @param {number} arity
 * @returns {number[]}
 */
function moduleBytes(body,arity) {
  const type=[1,0x60,arity,...Array(arity).fill(0x7f),1,0x7f];
  const func=[1,0];
  const exported=[1,...utf8('f'),0,0];
  const code=[1,...section([0,...body,0x0b])];
  return [0,97,115,109,1,0,0,0,1,...section(type),3,...section(func),
    7,...section(exported),10,...section(code)];
}

/**
 * Experimental opt-in lowering of 1-4 argument, return-only bitvector
 * functions into diversified WebAssembly modules embedded inside JS wrappers.
 *
 * Contract: callers pass primitive signed Int32 Numbers for every parameter; no code observes
 * original function source/stack formatting or tampers with Wasm intrinsics.
 * The emitted public binary can be copied and statically disassembled.
 *
 * @param {string} source
 * @param {'module'|'commonjs'} sourceType
 * @param {{seed:string,names:string[],conditionalStrategy?:'auto'|'select'|'if'}} options
 * @returns {WasmI32Result}
 */
function lowerWasmI32Functions(source,sourceType,options) {
  if(typeof source!=='string'||!['module','commonjs'].includes(sourceType)||
     !options||typeof options.seed!=='string'||!options.seed||
     !Array.isArray(options.names)||options.names.some(x=>typeof x!=='string')||
      options.conditionalStrategy!==undefined&&
      !['auto','select','if'].includes(options.conditionalStrategy)) {
    throw new TypeError('Expected source, module type, seed and explicit function names');
  }
  const targets=new Set(options.names);
  if(!targets.size)return {code:source,functions:0,instructions:0,wasmBytes:0,declined:0};
  const ast=parse(source,sourceType);
  /** @type {Set<string>} */
  const used=new Set();
  let dynamic=false;
  walk(ast,node=>{
    if(node.type==='Identifier') {
      used.add(node.name);
      if(node.name==='eval')dynamic=true;
    }
    if(node.type==='WithStatement')dynamic=true;
  });
  if(dynamic||observesFunctionSource(ast)||used.has('globalThis')||
     used.has('WebAssembly')||used.has('Uint8Array')) {
    return {code:source,functions:0,instructions:0,wasmBytes:0,declined:targets.size};
  }
  /** @type {Map<string,AstNode[]>} */
  const functions=new Map();
  for(const statement of ast.body) {
    const node=statement.type==='ExportNamedDeclaration'&&statement.declaration?
      statement.declaration:statement;
    if(node.type!=='FunctionDeclaration'||!node.id||!targets.has(node.id.name))continue;
    const matches=functions.get(node.id.name)??[];
    matches.push(node);
    functions.set(node.id.name,matches);
  }
  /** @type {import('./ast').Edit[]} */
  const edits=[];
  /** @type {string[]} */
  const init=[];
  let count=0,instructions=0,wasmBytes=0,declined=0;
  for(const name of targets) {
    const matches=functions.get(name);
    if(!matches||matches.length!==1) {declined++;continue;}
    const fn=matches[0];
    const parameters=/** @type {AstNode[]} */ (fn.params);
    const names=/** @type {string[]} */ (
      parameters.filter(param=>param.type==='Identifier').map(param=>param.name));
    const validParameters=parameters.length>=1&&parameters.length<=4&&
      names.length===parameters.length&&new Set(names).size===names.length;
    const statements=fn.body.body;
    const expression=statements[0]?.argument;
    if(fn.async||fn.generator||!validParameters||
      statements.length!==1||statements[0].type!=='ReturnStatement'||
      !expression||!accepted(expression,names)||
      !['BinaryExpression','UnaryExpression','ConditionalExpression'].includes(expression.type)||
       resultKind(expression)==='mixed') {
      declined++;continue;
    }
    const entropy=createHash('sha256').update(options.seed).update('\0')
      .update(name).update('\0').update(source).digest();
    const state={position:0,steps:0,diversified:0};
    const binary=moduleBytes(emit(expression,names,entropy,state,
      options.conditionalStrategy??'auto'),names.length);
    if(!WebAssembly.validate(Uint8Array.from(binary)))throw Error('Wasm compiler generated invalid bytecode');
    let helper='_wi_'+entropy.subarray(2,10).toString('hex');
    for(let nonce=1;used.has(helper)||source.includes(helper);nonce++) {
      helper='_wi_'+createHash('sha256').update(options.seed+'\0'+name+'\0'+nonce)
        .digest('hex').slice(0,16);
    }
    used.add(helper);
    // COO client-side synchronous compilation must count toward cold budget.
    const instance='new globalThis.WebAssembly.Instance(new '+
      'globalThis.WebAssembly.Module(globalThis.Uint8Array.from('+
      JSON.stringify(binary)+'))).exports.f';
    const helperParameters=names.length===1?'input':names.map((_,i)=>'input'+i).join(',');
    const callParameters=names.join(',');
    if(sourceType==='module') {
      // A cyclic importer may call this exported function before this
      // module's body has evaluated. A hoisted function binding exists during
      // module instantiation, whereas an eager const helper is still in TDZ.
      // Replace the helper with the Wasm export on its first invocation so
      // subsequent hot calls have no per-call initialization branch.
      init.push('function '+helper+'('+helperParameters+'){'+helper+'='+instance+
        ';return '+helper+'('+helperParameters+');}');
    } else {
      init.push('const '+helper+'='+instance+';');
    }
    const unsigned=resultKind(expression)==='unsigned';
    edits.push({start:fn.body.start,end:fn.body.end,
      text:'{return '+(unsigned?'('+helper+'('+callParameters+')>>>0)':
        helper+'('+callParameters+')')+';}'});
    count++;instructions+=state.steps;wasmBytes+=binary.length;
  }
  if(!count)return {code:source,functions:0,instructions:0,wasmBytes:0,declined};
  const rewritten=applyEdits(source,edits);
  // Hoisted functions may be invoked by later top-level statements.
  let offset=0;
  if(source.startsWith('#!')) {
    const newline=source.indexOf('\n');
    offset=newline<0?source.length:newline+1;
  }
  for(const statement of ast.body) {
    if(statement.type==='ExpressionStatement'&&statement.directive)offset=statement.end;
    else break;
  }
  const code=rewritten.slice(0,offset)+'\n'+init.join('\n')+'\n'+rewritten.slice(offset);
  parse(code,sourceType);
  return {code,functions:count,instructions,wasmBytes,declined};
}

module.exports={lowerWasmI32Functions};
